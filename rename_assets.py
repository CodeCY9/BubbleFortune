def rename_files():
    extracted_dir = r"d:\CRepository\BubbleFortune\asset\extracted"
    out_dir = r"d:\CRepository\BubbleFortune\asset\named_assets"
    os.makedirs(out_dir, exist_ok=True)
    
    counts = defaultdict(int)
    
    for i in range(1, 245):
        old_path = os.path.join(extracted_dir, f"{i}.png")
        if not os.path.exists(old_path):
            continue
            
        base_name = names.get(i, f"unknown_asset_{i}")
        counts[base_name] += 1
        
        # If there are duplicates, append a number
        if counts[base_name] > 1:
            new_name = f"{base_name}_{counts[base_name]}.png"
        else:
            new_name = f"{base_name}.png"
            
        new_path = os.path.join(out_dir, new_name)
        
        # Move and rename
        os.rename(old_path, new_path)
        
    print(f"Renamed and moved {sum(counts.values())} files to {out_dir}")

if __name__ == "__main__":
    rename_files()
