let currentLanguage: LanguagePreference = DEFAULT_LANGUAGE;
const languageListeners = new Set<() => void>();

export function getLanguage(): LanguagePreference {
  return currentLanguage;
}

export function setLanguage(language: LanguagePreference): void {
  if (currentLanguage === language) return;
  currentLanguage = language;
  languageListeners.forEach((listener) => listener());
}

export function initializeLanguage(language: LanguagePreference): void {
  currentLanguage = language;
}

export function subscribeLanguage(listener: () => void): () => void {
  languageListeners.add(listener);
  return () => languageListeners.delete(listener);
}

export function useLanguage(): LanguagePreference {
  return useSyncExternalStore(subscribeLanguage, getLanguage, getLanguage);
}

